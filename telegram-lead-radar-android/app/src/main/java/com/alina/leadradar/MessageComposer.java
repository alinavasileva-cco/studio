package com.alina.leadradar;

public final class MessageComposer {
    private MessageComposer() {}

    public static String compose(Lead lead, String profileUrl) {
        String link = profileUrl == null ? "" : profileUrl.trim();
        String suffix = link.isEmpty() ? "" : "\n\nПримеры и информация обо мне: " + link;

        switch (lead.category) {
            case SITE:
                return "Здравствуйте! Увидела ваш запрос на сайт. Могу собрать аккуратный сайт-визитку или лендинг: структура, дизайн, адаптив под телефон и запуск. Если задача ещё актуальна, могу быстро оценить объём и предложить вариант по срокам и стоимости." + suffix;
            case PRESENTATION:
                return "Здравствуйте! Увидела ваш запрос на презентацию. Могу собрать её под ключ: логика и структура, тексты, визуальная подача, единый дизайн и финальный PDF. Если задача ещё актуальна, пришлите материалы — быстро оценю объём и стоимость." + suffix;
            case CONSULTING:
            default:
                return "Здравствуйте! Увидела ваш запрос на бизнес-консультацию. Работаю с диагностикой бизнеса, стратегией роста, коммерческой функцией, P&L и настройкой процессов. Если запрос ещё актуален, могу коротко созвониться, разобраться в задаче и предложить формат работы." + suffix;
        }
    }
}
